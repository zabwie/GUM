#!/usr/bin/env python3
"""FROZEN benchmark for the perf-auto optimization run (2026-11-13).

Contract (owner-approved before the run started):
- Target: the production GUM CUDA decoder (benchmarks/real_decode), not PyTorch.
- Baseline config = the installed gum_openai_server.py launch flags exactly.
- 20 hand-authored diverse natural-language prompts (no templates, no JSON),
  buckets 128 / 1k / 4k prompt tokens, 256 generated tokens each, greedy.
- Warmup turn (excluded) precedes every sweep; a sweep = one fresh decoder
  process fed all selected prompts sequentially, mirroring server conditions.
- Correctness gate: every measured turn's committed token IDs must match the
  baseline golden token-for-token (all 256). Harness diffs session_ids against
  golden/ files captured from the unmodified baseline binary. Equivalent to
  the decoder's --expect-ids gate, extended to multi-turn session feeds.
- Prefill tok/s = prompt_tokens / spec_summary.prefill_s (decoder CUDA-event
  timing). Decode tok/s = spec_summary.tok_per_s (committed decode tokens).
  Wall clock recorded as a cross-check.

Do not edit this file or the prompt modules while the run is in progress.
Record every deviation in LOG.md.
"""

from __future__ import annotations

from collections import deque
import argparse
import hashlib
import json
import os
import shlex
import statistics
import subprocess
import sys
import time
from pathlib import Path

from jinja2 import Environment
from llama_cpp import Llama

sys.path.insert(0, str(Path(__file__).resolve().parent))
from perf_auto_prompts_short import PROMPTS_SHORT  # 7 prompts, ~128 tokens
from perf_auto_prompts_mid import PROMPTS_MID      # 7 prompts, ~1k tokens
from perf_auto_prompts_long import PROMPTS_LONG    # 6 prompts, ~4k tokens

ROOT = Path(__file__).resolve().parents[1]
TARGET = Path(os.environ.get("GUM_TARGET_MODEL",
    Path.home() / "Desktop/Chip/models/Qwen3.8-27B-STRICT-Q4_0.gguf"))
MTP = Path(os.environ.get("GUM_MTP_MODEL",
    Path.home() / "Desktop/Chip/models/mtp-Qwen3.8-27B-Q4_0.gguf"))
DECODER = Path(os.environ.get("GUM_DECODER", ROOT / "benchmarks/real_decode"))
OUT = ROOT / "results/perf-auto"
SEED = 20261113
GEN_TOKENS = 256
CPUS = "0-3"

PROMPTS = [("short", name, text) for name, text in PROMPTS_SHORT] \
        + [("mid", name, text) for name, text in PROMPTS_MID] \
        + [("long", name, text) for name, text in PROMPTS_LONG]

WARMUP = ("Warmup: In one short paragraph, describe how a bicycle bell works "
          "and why the sound carries better on a quiet street than near traffic.")

# Baseline = the installed server configuration (gum_openai_server.py), verbatim.
BASE_FLAGS = ["--session", "1", "--session-tail", "1", "--session-stream", "1",
              "--prefill-chunks", "8", "--speculate", "32", "--packed-verify", "1",
              "--pld", "0", "--draft-max", "31", "--ctx", "196608", "--gen-tokens", "131072",
              "--hot-mib", "3456", "--cache-mib", "10240", "--kv-cache", "turboquant-ttkv",
              "--show-text", "0", "--measure-h2d", "1"]


def record(line: str) -> dict:
    return dict(field.split("=", 1) for field in line.strip().split(",") if "=" in field)


def gpu_snapshot() -> dict:
    try:
        used = subprocess.check_output(["nvidia-smi", "--query-gpu=memory.used,memory.total",
                                        "--format=csv,noheader,nounits"], text=True).strip()
        u, t = used.split(",")
        return {"vram_used_MiB": int(u), "vram_total_MiB": int(t)}
    except Exception as exc:
        return {"vram_error": str(exc)}


def launch(extra_flags: list[str], log_path: Path) -> subprocess.Popen:
    command = ["stdbuf", "-oL", "-eL", "taskset", "-c", CPUS, str(DECODER),
               "--model", str(TARGET), "--mtp", str(MTP), *BASE_FLAGS, *extra_flags,
               "--prompt-ids", "-"]
    log_path.write_text(shlex.join(command) + "\n")
    return subprocess.Popen(command, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, text=True, errors="replace", bufsize=1)


def run_turn(proc: subprocess.Popen, ids: list[int], log: "TextIO") -> dict:
    """Feed one turn, collect stdout until session_ids. Returns parsed turn data."""
    payload = f"{GEN_TOKENS}:" + ",".join(map(str, ids))
    started = time.monotonic()
    proc.stdin.write(payload + "\n")
    proc.stdin.flush()
    summary, turn, lossless = {}, {}, {}
    out_ids = None
    cycles = 0
    cold_bytes = 0
    cold_h2d_ms = 0.0
    log_tail: deque[str] = deque(maxlen=40)
    for line in proc.stdout:
        log_tail.append(line)
        log.write(line)
        if line.startswith("spec_cycle,"):
            cycles += 1
            row = record(line)
            cold_bytes += int(row.get("cold_bytes", 0))
            cold_h2d_ms += float(row.get("cold_h2d_ms", 0.0))
        elif line.startswith("spec_summary,"):
            summary = record(line)
        elif line.startswith("session_turn,"):
            turn = record(line)
        elif line.startswith("session_ids"):
            out_ids = [int(v) for v in line.split(",")[1:] if v]
            break
    wall = time.monotonic() - started
    if out_ids is None or not summary:
        tail_text = "".join(log_tail)[-4000:] if log_tail else "(no tail)"
        raise RuntimeError(f"decoder did not finish the turn; log tail:\n{tail_text}")
    return {"out_ids": out_ids, "summary": summary, "turn": turn, "wall_s": round(wall, 4),
            "cycles": cycles, "cold_bytes": cold_bytes, "cold_h2d_ms": round(cold_h2d_ms, 1),
            "prompt_tokens": len(ids)}


def token_ok(prompt_tokens: int) -> str:
    if prompt_tokens <= 200:
        return "128"
    if prompt_tokens <= 1300:
        return "1k"
    if prompt_tokens <= 4600:
        return "4k"
    return "over"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("tag", help="run tag, e.g. baseline or a candidate name")
    ap.add_argument("--golden", action="store_true",
                    help="capture goldens instead of benchmarking (1 sweep, ids saved)")
    ap.add_argument("--sweeps", type=int, default=3)
    ap.add_argument("--lengths", default="128,1k,4k")
    ap.add_argument("--flags", default="", help="extra decoder flags for a candidate")
    args = ap.parse_args()

    dest = OUT / args.tag
    dest.mkdir(parents=True, exist_ok=True)
    flags = shlex.split(args.flags)

    tok = Llama(str(TARGET), vocab_only=True, verbose=False)
    eos = tok.token_eos()
    template = Environment().from_string(tok.metadata["tokenizer.chat_template"])
    template.globals["raise_exception"] = lambda m: (_ for _ in ()).throw(ValueError(m))

    def render(text: str) -> list[int]:
        rendered = template.render(messages=[{"role": "user", "content": text}],
                                   tools=[], add_generation_prompt=True, enable_thinking=False)
        return tok.tokenize(rendered.encode("utf-8"), add_bos=False, special=True)

    prepared = []
    bucket_map = {"short": "128", "mid": "1k", "long": "4k"}
    for bucket, name, text in PROMPTS:
        ids = render(text)
        prepared.append({"bucket": token_ok(len(ids)), "name": name, "ids": ids,
                         "declared": bucket_map[bucket], "prompt_tokens": len(ids)})
        (dest / f"prompt.{name}.ids").write_text(",".join(map(str, ids)) + "\n")
    warm_ids = render(WARMUP)

    selected = [p for p in prepared if p["declared"] in args.lengths.split(",")]
    if not selected and not args.golden:
        sys.exit("no prompts selected")

    manifest = {"tag": args.tag, "seed": SEED, "gen_tokens": GEN_TOKENS,
                "flags": flags, "base_flags": BASE_FLAGS, "gpu": gpu_snapshot(),
                "prompts": [{k: v for k, v in p.items() if k != "ids"} for p in prepared],
                "decoder_sha": hashlib.sha256(DECODER.read_bytes()).hexdigest()[:16]}
    (dest / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest["gpu"]), flush=True)
    for p in prepared:
        print(f"prompt {p['name']}: declared={p['declared']} tokens={p['prompt_tokens']}", flush=True)

    gold_dir = OUT / "golden"
    if args.golden:
        gold_dir.mkdir(parents=True, exist_ok=True)
        log = (dest / "golden.log").open("w")
        proc = launch(flags, dest / "command.txt")
        try:
            run_turn(proc, warm_ids, log)
            for p in prepared:
                data = run_turn(proc, p["ids"], log)
                (gold_dir / f"{p['name']}.ids").write_text(
                    "\n".join(map(str, data["out_ids"])) + "\n")
                print(f"golden {p['name']}: {len(data['out_ids'])} ids, "
                      f"tok_per_s={data['summary'].get('tok_per_s')}", flush=True)
        finally:
            proc.stdin.close()
            proc.wait(timeout=30)
        log.close()
        return

    goldens = {}
    for p in prepared:
        g = gold_dir / f"{p['name']}.ids"
        if not g.is_file():
            sys.exit(f"missing golden for {p['name']}; run --golden on the baseline first")
        goldens[p["name"]] = [int(x) for x in g.read_text().split()]

    sweep_rows = []
    def one_sweep(sweep: int, append: bool) -> None:
        log = (dest / f"sweep{sweep}.log").open("a" if append else "w")
        proc = launch(flags, dest / f"command_sweep{sweep}.txt")
        try:
            run_turn(proc, warm_ids, log)
            for p in selected:
                data = run_turn(proc, p["ids"], log)
                s = data["summary"]
                got = data["out_ids"]
                expect = goldens[p["name"]]
                mism = next((i for i, (a, b) in enumerate(zip(got, expect)) if a != b), None)
                exact = mism is None and len(got) == len(expect)
                row = {"sweep": sweep, "name": p["name"], "bucket": p["declared"],
                       "prompt_tokens": data["prompt_tokens"],
                       "prefill_tok_per_s": round(data["prompt_tokens"] / float(s["prefill_s"]), 2),
                       "decode_tok_per_s": float(s["tok_per_s"]),
                       "committed": len(got) - got.count(eos),
                       "emitted_per_cycle": float(s["mean_emitted_per_cycle"]),
                       "acceptance": float(s["draft_acceptance"]),
                       "mean_verify_s": float(s["mean_verify_s"]),
                       "mean_cycle_s": float(s["mean_cycle_s"]),
                       "prefill_s": float(s["prefill_s"]),
                       "decode_s": float(s["decode_s"]),
                       "wall_s": data["wall_s"],
                       "cold_bytes": data["cold_bytes"],
                       "cold_gb_s": round(data["cold_bytes"] / max(data["cold_h2d_ms"], 1) / 1e6, 2),
                       "min_free_vram_MiB": int(s["min_free_vram_MiB"]),
                       "exact_vs_baseline": exact,
                       "first_mismatch": mism,
                       "gpu_after_turn": gpu_snapshot()}
                sweep_rows.append(row)
                print(json.dumps(row), flush=True)
                if not exact:
                    print(f"LOSSLESS VIOLATION on {p['name']} at token {mism}", flush=True)
        finally:
            try:
                proc.stdin.close()
                proc.wait(timeout=30)
            except Exception:
                proc.kill()
        log.close()

    for sweep in range(args.sweeps):
        for attempt in range(3):
            try:
                one_sweep(sweep, append=attempt > 0)
                break
            except RuntimeError as error:
                print(f"RETRY sweep {sweep} attempt {attempt}: {str(error)[-600:]}", flush=True)
                if attempt == 2:
                    raise
                time.sleep(120)  # kernel: settle swap before relaunch

    (dest / "rows.jsonl").write_text("".join(json.dumps(r) + "\n" for r in sweep_rows))
    # Aggregate: median and spread per bucket per metric across sweeps and prompts.
    agg = {}
    for bucket in ("128", "1k", "4k"):
        rows = [r for r in sweep_rows if r["bucket"] == bucket]
        if not rows:
            continue
        entry = {"n": len(rows)}
        for metric in ("prefill_tok_per_s", "decode_tok_per_s"):
            vals = [r[metric] for r in rows]
            entry[metric] = {"median": round(statistics.median(vals), 3),
                             "min": min(vals), "max": max(vals),
                             "spread_pct": round((max(vals) - min(vals)) /
                                                 max(statistics.median(vals), 1e-9) * 100, 1)}
        entry["exact_all"] = all(r["exact_vs_baseline"] for r in rows)
        agg[bucket] = entry
    (dest / "aggregate.json").write_text(json.dumps(agg, indent=2) + "\n")
    print("AGG " + json.dumps(agg), flush=True)
    if not all(e["exact_all"] for e in agg.values()):
        sys.exit("correctness gate FAILED — do not keep this candidate")


if __name__ == "__main__":
    main()
